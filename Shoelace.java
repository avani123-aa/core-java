class Shoelace{

String brand;
String colour;
String material;
double length;
double width;
String type;
String shape;
boolean elastic;
double price;
String originCountry;

Shoelace(){
}

Shoelace(String brand,String colour,String material,double length,double width,String type,String shape,boolean elastic,double price,String originCountry){
this.brand=brand;
this.colour=colour;
this.material=material;
this.length=length;
this.width=width;
this.type=type;
this.shape=shape;
this.elastic=elastic;
this.price=price;
this.originCountry=originCountry;
}

}