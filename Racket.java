class Racket{

String brand;
String sport;
String colour;
String material;
double weight;
double length;
String gripType;
double price;
int stringCount;
String originCountry;

Racket(){
}

Racket(String brand,String sport,String colour,String material,double weight,double length,String gripType,double price,int stringCount,String originCountry){
this.brand=brand;
this.sport=sport;
this.colour=colour;
this.material=material;
this.weight=weight;
this.length=length;
this.gripType=gripType;
this.price=price;
this.stringCount=stringCount;
this.originCountry=originCountry;
}

}