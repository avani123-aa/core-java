class Blanket{

String brand;
String colour;
String material;
double price;
double length;
double width;

Blanket(){
}

Blanket(String brand,String colour,String material,double price,double length,double width){
this.brand=brand;
this.colour=colour;
this.material=material;
this.price=price;
this.length=length;
this.width=width;
}

}