class Bucket
{
    String material;
    String color;
    int capacity;
    double price;
    String brand;   
	
    Bucket()
    {
    }

    Bucket(String material, String color, int capacity, double price, String brand)
    {
        this.material = material;
        this.color = color;
        this.capacity = capacity;
        this.price = price;
        this.brand = brand;
    }
}